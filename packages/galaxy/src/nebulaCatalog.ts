/**
 * Famous nebulae with their real positions (J2000), distances, apparent sizes and
 * integrated V magnitudes (rounded literature values), plus the structural model used
 * to build each one's volume (nebulae.ts). The 3D structure is modeled from published
 * morphology; the depth along the line of sight is assumed from the apparent size.
 */
import type { NebulaModel, NebulaPalette } from './nebulae';

export type NebulaKind = 'emission' | 'reflection' | 'planetary' | 'snr' | 'dark';

export interface NebulaInfo {
  id: string;
  name: string;
  designation: string;
  kind: NebulaKind;
  /** ICRS RA/Dec of the centre, degrees. */
  ra: number;
  dec: number;
  distPc: number;
  distanceSource: string;
  /** Apparent size (major, minor), arcmin, and position angle of the major axis (deg, E of N). */
  sizeArcmin: [number, number];
  paDeg: number;
  /** Line-of-sight depth relative to the mean apparent size. */
  depth: number;
  /** Integrated apparent V magnitude. */
  vmag: number;
  /** Peak dust extinction through the volume, mag. */
  dustPeakAv: number;
  model?: NebulaModel;
  palette: NebulaPalette;
  /** Named stars (catalogue ids) that ionise or light the nebula. */
  sources?: string[];
  facts: string[];
}

