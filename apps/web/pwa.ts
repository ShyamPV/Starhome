import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Plugin } from 'vite';

/** Public files cached on install: the app's identity and the core catalogue. */
const PUBLIC_PRECACHE = ['favicon.svg', 'manifest.webmanifest', 'icon-192.png', 'icon-512.png', 'data/exoplanets.json'];

/**
 * Emits sw.js at build time with the exact list of hashed build outputs, so the app
 * shell and core catalogue work offline. Strategy:
 * - page loads: network first, falling back to the cached shell when offline;
 * - build assets and precached data: cache first (names change when content changes);
 * - textures and optional catalogues (public/textures, public/data): cached the first
 *   time they are used, so places you have visited stay available offline.
 * The cache name carries a hash of everything precached; a new build installs alongside
 * the old one and the page offers a reload to switch.
 */
export function serviceWorker(publicDir: string): Plugin {
  return {
    name: 'starhome-service-worker',
    apply: 'build',
    generateBundle(_, bundle) {
      const built = Object.keys(bundle).filter((f) => !f.endsWith('.map'));
      const extra = PUBLIC_PRECACHE.filter((f) => existsSync(join(publicDir, f)));
      const hash = createHash('sha256');
      for (const f of built.sort()) hash.update(f);
      for (const f of extra) hash.update(readFileSync(join(publicDir, f)));
      const version = hash.digest('hex').slice(0, 12);
      const precache = ['./', ...built.filter((f) => f !== 'index.html'), ...extra];
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: swSource(version, precache) });
    },
  };
}

function swSource(version: string, precache: string[]): string {
  return `// Generated by apps/web/pwa.ts. Do not edit.
const VERSION = ${JSON.stringify(version)};
const SHELL = 'starhome-shell-' + VERSION;
const RUNTIME = 'starhome-runtime-v1';
const PRECACHE = ${JSON.stringify(precache)};
const scoped = (path) => new URL(path, self.registration.scope).href;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(SHELL).then((cache) => cache.addAll(PRECACHE.map((p) => new Request(scoped(p), { cache: 'reload' })))));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) if (key.startsWith('starhome-shell-') && key !== SHELL) await caches.delete(key);
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(async () => (await caches.match(scoped('./'), { ignoreVary: true })) || Response.error()),
    );
    return;
  }
  event.respondWith(
    (async () => {
      // Module scripts carry an Origin header and the server varies on it; these are same-origin static files.
      const hit = await caches.match(request, { ignoreVary: true });
      if (hit) return hit;
      const response = await fetch(request);
      const path = url.pathname;
      if (response.ok && (path.includes('/textures/') || path.includes('/data/'))) {
        const cache = await caches.open(RUNTIME);
        await cache.put(request, response.clone());
      }
      return response;
    })(),
  );
});
`;
}
